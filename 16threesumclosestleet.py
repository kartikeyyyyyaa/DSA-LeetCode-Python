class Solution:
    def threeSumClosest(self, nums: list[int], tar: int) -> int:
        nums.sort()
        minv = float('inf')
        ans = 0

        for i in range(len(nums) - 2):
            j = i + 1
            k = len(nums) - 1

            while j < k:
                s = nums[i] + nums[j] + nums[k]
                a = tar - s
                if a < 0:
                    a = -a

                if a < minv:
                    minv = a
                    ans = s

                if s < tar:
                    j += 1
                elif s > tar:
                    k -= 1
                else:
                    return s
        print(ans)
        return ans

